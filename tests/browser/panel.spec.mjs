import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';

const fixture = () => JSON.parse(readFileSync('artifacts/panel-session.json', 'utf8'));
const authorize = async context => context.addCookies([{ name: 'sessionid', value: fixture().cookie, domain: '127.0.0.1', path: '/', httpOnly: true, sameSite: 'Lax' }]);
const save = async page => {
  await Promise.all([page.waitForNavigation({ waitUntil: 'domcontentloaded' }), page.getByRole('button', { name: 'Guardar cambios' }).click()]);
  await expect(page.getByText('Cambios guardados correctamente.', { exact: true })).toBeVisible();
};
const panorama = 'static/panoramas/demo-azul.png';
const otherPanorama = 'static/panoramas/demo-ambar.png';
const sceneURL = (tour, scene) => `/panel/recorridos/${tour}/escenas/${scene}/`;
const at = async (page, x = .6, y = .4) => {
  const b = await page.locator('#editor-scene canvas').boundingBox();
  return { x: b.x + b.width * x, y: b.y + b.height * y };
};
const addPoint = async (page, destination, label) => {
  await expect(page.locator('#main')).toHaveAttribute('data-loading', 'false');
  await page.getByRole('button', { name: 'Añadir punto', exact: true }).click();
  const hit = await at(page); await page.mouse.click(hit.x, hit.y);
  await page.getByLabel('Etiqueta', { exact: true }).fill(label);
  await page.getByLabel('Escena de destino', { exact: true }).selectOption(String(destination));
  await page.getByRole('button', { name: 'Guardar punto', exact: true }).click();
  await expect(page.locator('#editor-feedback')).toHaveText('Punto guardado.');
};

